#!/usr/bin/env python3
"""Build CLI documentation and a man page from Mercury's executable help."""
import argparse
import ast
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def help_text(*arguments):
    result = subprocess.run([sys.executable, str(ROOT / 'mercury'), *arguments, '--help'],
                            capture_output=True, text=True, check=True,
                            env=dict(os.environ, COLUMNS='88'))
    return result.stdout.replace(str(ROOT / 'mercury'), 'mercury').rstrip()


def outputs():
    tree = ast.parse((ROOT / 'mercury_server.py').read_text())
    version = next(ast.literal_eval(n.value) for n in tree.body
                   if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'VERSION' for t in n.targets))
    main = help_text()
    commands = max(re.findall(r'\{([a-z,-]+)\}', main), key=lambda value: value.count(',')).split(',')
    sections = [('mercury', main)] + [('mercury ' + name, help_text(name)) for name in commands]
    sys.path.insert(0, str(ROOT))
    from mercury_terminal import mini_help
    md = ['# Mercury CLI ' + version, '', 'Generated by `python3 tools/command_reference.py`. Run with `--check` to detect drift.', '',
          'Help generation does not start the server or open a manuscript.', '']
    manual = ['.TH MERCURY 1 "" "Mercury Writer ' + version + '" "User Commands"',
              '.SH NAME', r'mercury \- Mercury Library, writing editors and manuscript synchronization']
    def roff(text):
        return '\n'.join((r'\&' if line.startswith(('.', "'")) else '') + line.replace('\\', r'\e') for line in text.splitlines())
    for name, text in sections:
        md += ['## ' + name, '', '```text', text, '```', '']
        manual += ['.SH "' + name.upper() + '"', '.nf', roff(text), '.fi']
    md += ['## Mini keyboard reference', '']
    manual += ['.SH MINI KEYBOARD REFERENCE']
    for title, bindings in mini_help():
        md += ['### ' + title, '']
        manual += ['.SS ' + title]
        for key, description in bindings:
            md.append('- **' + key + '**: ' + description)
            manual += ['.TP', roff(key), roff(description)]
        md.append('')
    return {ROOT / 'docs/CLI.md': '\n'.join(md), ROOT / 'mercury.1': '\n'.join(manual) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit('Regenerate Mercury references: ' + ', '.join(stale))
    print('Mercury command references synchronized')


if __name__ == '__main__': main()
